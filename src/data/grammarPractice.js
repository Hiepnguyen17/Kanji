export function practiceQuestions(pattern, level) {
  const key = `${level}|${pattern.formula}`;
  const existing = (pattern.examples || [])
    .filter(item => item.japanese?.trim() && item.meaning_vi?.trim())
    .map(item => ({ japanese: item.japanese.trim(), meaning: item.meaning_vi.trim(), reading: item.reading || '' }));
  const authored = (grammarPractice[key] || []).map(([japanese, meaning]) => ({ japanese, meaning, reading: '' }));
  const seen = new Set();
  return [...existing, ...authored].filter(item => {
    if (seen.has(item.japanese)) return false;
    seen.add(item.japanese);
    return true;
  });
}
